#!/usr/bin/env python3
"""Compile the small EEL expression subset used by the two audited SteamPipe kernels.

This is a build-time translator, not a runtime dependency or general EEL compiler.
All state uses doubles; each feedback access remains in the same sample iteration.
Unsupported syntax fails rather than silently changing DSP.
"""
import json,pathlib,re
ROOT=pathlib.Path(__file__).resolve().parents[2]
FOLDER=ROOT/'synthdefs/Defaults/SteamPipeBox'
PRECEDENCE={'=':1,'+=':1,'-=':1,'*=':1,'/=':1,'||':3,'&&':4,'==':5,'!=':5,'<':6,'>':6,'<=':6,'>=':6,'+':7,'-':7,'*':8,'/':8}
class Parser:
 def __init__(self,s):
  self.tokens=re.findall(r'\d*\.\d+(?:[eE][+-]?\d+)?|\d+(?:[eE][+-]?\d+)?|[A-Za-z_][A-Za-z_0-9]*|==|!=|>=|<=|&&|\|\||\+=|-=|\*=|/=|[^\s]',s);self.i=0
 def peek(self):return self.tokens[self.i] if self.i<len(self.tokens) else ''
 def take(self,expect=None):
  t=self.peek();assert t and (expect is None or t==expect),(expect,t,self.tokens[max(0,self.i-8):self.i+8]);self.i+=1;return t
 def expression(self,minimum=1):
  t=self.take()
  if t in ['-','+','!']:left='('+t+self.expression(9)+')'
  elif t=='(':
   seq=[]
   while self.peek()!=')':
    seq.append(self.expression());
    if self.peek()!=';':break
    self.take(';')
   self.take(')')
   left=('('+seq[0]+')') if len(seq)==1 else '([&]() -> double {'+''.join(x+';' for x in seq[:-1])+'return '+seq[-1]+';}())'
  else:left=t
  while True:
   op=self.peek()
   if op=='(':
    self.take();args=[]
    while self.peek()!=')':
     args.append(self.expression())
     if self.peek()!=',':break
     self.take(',')
    self.take(')');left=left+'('+','.join(args)+')';continue
   if op=='[':
    self.take();index=self.expression();self.take(']');left=left+'[static_cast<int>('+index+')]';continue
   if op=='?' and minimum<=2:
    self.take();yes=self.expression()
    no='0.0'
    if self.peek()==':':self.take();no=self.expression(2)
    left='('+left+' ? '+yes+' : '+no+')';continue
   prec=PRECEDENCE.get(op,0)
   if prec<minimum:break
   self.take();right=self.expression(prec if prec==1 else prec+1);left='('+left+op+right+')'
  return left
 def statements(self):
  out=[]
  while self.peek():out.append(self.expression());self.take(';')
  return ''.join(s+';\n' for s in out)
def translate(path,name):
 source=re.sub(r'//[^\n]*','',path.read_text());init,sample=source.split('@sample');init=init.replace('@init','')
 functions=[]
 # Balanced function bodies, including their optional local(...) declaration.
 pattern=r'function\s+(\w+)\(([^)]*)\)\s*(?:local\(([^)]*)\)\s*)?\('
 while (m:=re.search(pattern,init)):
  end=m.end();depth=1
  while depth:
   depth+=(init[end]=='(')-(init[end]==')');end+=1
  assert init[end]==';'
  fn,args,locals_=m.groups();body=init[m.end():end-1];functions.append((fn,args,locals_ or '',body));init=init[:m.start()]+init[end+1:]
 params=sorted(set(re.findall(r'(?<![A-Za-z0-9_])(_[A-Za-z0-9_]+)',source)))
 # All non-local identifiers are persistent kernel state (EEL defaults to zero).
 ids=set(re.findall(r'\b[A-Za-z_]\w*\b',init+sample));fnnames={f[0] for f in functions}
 builtins={'sin','cos','tan','atan','exp','pow','sqrt','floor','ceil','abs','min','max','mod','clip','buf','srate','f32','niPitch','niTimeRate','niDelay','niFilterF','niFilterD'}
 globals_=ids-builtins-fnnames
 code=f'struct {name} {{\n double* buf=nullptr; double srate=48000;\n'
 code+=''.join(f' double {v}=0;\n' for v in sorted(globals_))
 for fn,args,local,body in functions:
  argv=[a.strip() for a in args.split(',') if a.strip()];loc=[a.strip() for a in local.split(',') if a.strip()]
  expr=Parser('('+body+')').expression()
  code+='double '+fn+'('+','.join('double '+a for a in argv)+') {\n'+''.join('double '+a+'=0;\n' for a in loc)+'return '+expr+';\n}\n'
 code+='void init() {\n'+Parser(init).statements()+'}\n'
 code+='void sample() {\n'+Parser(sample).statements()+'}\n};\n'
 return code,params

def main():
 grid=json.loads((FOLDER/'primary-filter-grid.json').read_text())
