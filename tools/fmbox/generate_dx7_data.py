#!/usr/bin/env python3
"""Extract upstream DX7 tables verbatim; keep the adaptation reproducible."""
import json,pathlib,re
ROOT=pathlib.Path(__file__).resolve().parents[2]
s=(ROOT/'synthdefs/Defaults/FMBox/upstream/DX7.scd.txt').read_text()
def array(name):
    m=re.search(r'\b'+re.escape(name)+r'\s*=\s*#\[([^]]*)\]',s,re.S)
    assert m,name
    return json.loads('['+re.sub(r'/\*.*?\*/|//[^\n]*','',m[1],flags=re.S)+']')
# Matrix stores 1 for each 4pi link; feedback remains the selected cell's multiplier.
m=re.search(r'wf = Array2D.fromArray\(32, 42, \[(.*?)\]\)',s,re.S)
a=re.sub(r'/\*.*?\*/|//[^\n]*','',m[1],flags=re.S).replace('(pi * 4)','1')
alg=json.loads('['+a+']');assert len(alg)==32*42
fields=[('Algorithm','algorithm',31,0),('Feedback','feedback',7,0),('Transpose','transpose',48,24),('LFO Wave','lfo_wave',5,0),('LFO Speed','lfo_speed',99,35),('Pitch Sens','lfo_pms',7,0),('Pitch Depth','lfo_pmd',99,0),('Amp Depth','lfo_amd',99,0),('LFO Sync','lfo_sync',1,1),('LFO Delay','lfo_delay',99,0),('Osc Sync','osc_sync',1,1)]
fields += [('Pitch Rate '+str(i+1),'pitch_r'+str(i),99,0) for i in range(4)]
fields += [('Pitch Level '+str(i+1),'pitch_l'+str(i),99,50) for i in range(4)]
ops=[('Mode','mode',1,0),('Coarse','coarse',31,1),('Fine','fine',99,0),('Detune','detune',14,7),('Rate Scale','rate_scale',7,0)]
ops += [('Rate '+str(i+1),'r'+str(i),99,0 if i in (0,3) else 60) for i in range(4)]
ops += [('Level '+str(i+1),'l'+str(i),99,99 if i<3 else 0) for i in range(4)]
ops += [('Output','output',99,99),('Left Depth','left_depth',99,0),('Right Depth','right_depth',99,0),('Left Curve','left_curve',3,0),('Right Curve','right_curve',3,0),('Breakpoint','breakpoint',99,39),('Velocity','velocity',7,0),('Amp Sens','amp_sens',3,0)]
assert len(fields)==19 and len(ops)==21
header='''// Generated by tools/fmbox/generate_dx7_data.py from Aziz Ege Gonul's
// DX7-Supercollider (GPL-3.0). See synthdefs/Defaults/FMBox/upstream/LICENSE.md.
#pragma once
#include <array>
namespace scDX7 {
struct Field { const char* name; const char* sc; int max; int initial; };
'''
for name,data in [('globalFields',fields),('operatorFields',ops)]:
    header+=f'inline constexpr std::array<Field,{len(data)}> {name} = {{{{\n'
    header+=''.join('    {"%s","%s",%d,%d},\n'%tuple(row) for row in data)+'}};\n'
header+='inline constexpr int algorithms[32][42] = {\n'+''.join('    {'+','.join(map(str,alg[i*42:(i+1)*42]))+'},\n'for i in range(32))+'};\n'
header+='inline constexpr int feedbackCell[32] = {'+','.join(map(str,array('feedbackSel')))+'};\n}\n'
(ROOT/'src/nodes/scDX7Data.h').write_text(header)
data={n:array(n) for n in ['voice_eg_rate_rise_duration','dx7_voice_eg_rate_rise_percent','velTable','dx7_voice_lfo_frequency','dx7_voice_pms_to_semitones','dx7_voice_amd_to_ol_adjustment','dx7_voice_pitch_level_to_shift','feedbackIndex','outOscVol']}
data['feedbackSel']=array('feedbackSel')
# An include, not another Defaults script: startup sync must only build fmBox.scd.
inc='// Upstream conversion/measurement tables (GPL-3.0); generated, do not edit.\n(\n'
inc+=',\n'.join('    '+name+': '+str(v).replace('[','[').replace(']',']') for name,v in data.items())+'\n)\n'
(ROOT/'synthdefs/Defaults/FMBox/dx7Data.inc').write_text(inc)
